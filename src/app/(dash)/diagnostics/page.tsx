import fs from 'node:fs';
import { prisma } from '@/lib/db';
import { systemHealth } from '@/lib/health';
import { DATA_DIR } from '@/lib/paths';
import { Badge, fmtDate, PageHeader } from '@/components/ui';

export default async function DiagnosticsPage() {
  const [health, queues, workers] = await Promise.all([
    systemHealth(),
    prisma.queueJob.groupBy({ by: ['queue', 'status'], _count: { _all: true } }),
    prisma.workerStatus.findMany({ orderBy: { lastSeenAt: 'desc' } }),
  ]);
  const checks = [
    { label: 'Worker running (single-owner lock)', ok: health.worker.alive, detail: health.worker.reason },
    { label: 'Extension key generated', ok: health.extension.paired, detail: health.extension.paired ? 'Active key exists' : 'Settings → generate key' },
    { label: 'Extension connected (last 90s)', ok: health.extension.connected, detail: `Last seen ${fmtDate(health.extension.lastSeenAt)}${health.extension.version ? ` · v${health.extension.version}` : ''}` },
    { label: 'ChatGPT not in backoff', ok: !health.chatgpt.backoff && !health.chatgpt.pausedNewClaims, detail: health.chatgpt.reason ?? 'OK' },
    { label: 'Data directory writable', ok: (() => { try { fs.accessSync(DATA_DIR, fs.constants.W_OK); return true; } catch { return false; } })(), detail: DATA_DIR },
    { label: 'SESSION_SECRET configured', ok: (process.env.SESSION_SECRET ?? '').length >= 32, detail: 'Generated by npm run setup' },
  ];
  return (
    <>
      <PageHeader title="Diagnostics" description="Live checks only. Live ChatGPT/WordPress sessions are verified from the Websites page and by the extension." />
      <div className="card mb-6"><ul className="space-y-2 text-sm">{checks.map((c) => <li key={c.label} className="flex items-start gap-2"><Badge tone={c.ok ? 'success' : 'danger'}>{c.ok ? 'ok' : 'fail'}</Badge><span><b>{c.label}</b> — <span className="text-slate-500">{c.detail}</span></span></li>)}</ul></div>
      <div className="grid gap-6 md:grid-cols-2">
        <div className="card"><h2 className="mb-2 font-semibold">Queues</h2><table className="table"><thead><tr><th>Queue</th><th>Status</th><th>Jobs</th></tr></thead><tbody>{queues.map((q) => <tr key={q.queue + q.status}><td>{q.queue}</td><td>{q.status}</td><td>{q._count._all}</td></tr>)}</tbody></table></div>
        <div className="card"><h2 className="mb-2 font-semibold">Processes</h2><table className="table"><thead><tr><th>ID</th><th>Status</th><th>Last seen</th></tr></thead><tbody>{workers.map((w) => <tr key={w.id}><td className="text-xs">{w.id}</td><td>{w.status}</td><td className="text-xs">{fmtDate(w.lastSeenAt)}</td></tr>)}</tbody></table></div>
      </div>
    </>
  );
}
